class LocalizationManager(QObject):
    languageChanged = pyqtSignal(str)

    def __init__(self, config_manager: Any = None):
        super().__init__()
        self.config_manager = config_manager
        app = QApplication.instance()
        if app is not None:
            app.installEventFilter(self)
        stored = ""
        if config_manager is not None:
            app = config_manager.get_app_settings()
            stored = app.get("language", DEFAULT_LANGUAGE)
        self._language = stored if stored in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE

    def get_language(self) -> str:
        return self._language

    def eventFilter(self, watched: Any, event: QEvent) -> bool:
        if event.type() == QEvent.Type.Show:
            retranslate_application(self._language)
        return False

    def set_language(self, language: str, persist: bool = True) -> None:
        if language not in SUPPORTED_LANGUAGES:
            language = DEFAULT_LANGUAGE
        if self._language == language:
            return
        self._language = language
        if persist and self.config_manager is not None:
            self.config_manager.update_app_settings({"language": language})
        self.languageChanged.emit(language)
        retranslate_application(language)

    def t(self, key: str, **params: Any) -> str:
        text = TRANSLATIONS.get(self._language, {}).get(key)
        if text is None:
            text = TRANSLATIONS["en"].get(key)
        if text is None:
            text = TRANSLATIONS["en"].get(key, "Missing translation")
        if params:
            try:
                text = text.format(**params)
            except (KeyError, ValueError):
                pass
        return text


_manager: Optional[LocalizationManager] = None


def init_localization(config_manager: Any = None) -> LocalizationManager:
    global _manager
    if _manager is None or sip.isdeleted(_manager):
        _manager = LocalizationManager(config_manager)
    elif config_manager is not None:
        _manager.config_manager = config_manager
    return _manager


def get_localization() -> LocalizationManager:
    global _manager
    if _manager is None or sip.isdeleted(_manager):
        _manager = LocalizationManager(ConfigManager())
    return _manager


def tr(key: str, **params: Any) -> str:
    return get_localization().t(key, **params)


