def retranslate_application(language: str) -> None:
    app = QApplication.instance()
    if app is None:
        return
    mapping = LEGACY_TEXT.get(language, {})
    actions = {}
    for widget in app.allWidgets():
        for action in widget.findChildren(QAction):
            actions[id(action)] = action
        for action in widget.actions():
            actions[id(action)] = action
    for action in actions.values():
        old = action.text()
        if isinstance(old, str) and old in mapping:
            action.setText(mapping[old])

    for widget in app.allWidgets():
        try:
            if isinstance(widget, QTabWidget):
                if language == "en":
                    tab_names = ("Canvas & Grid", "Appearance", "Tools", "Tileset Import", "Keyboard Shortcuts")
                else:
                    tab_names = ("Siatka i płótno", "Wygląd", "Narzędzia", "Import tilesetów", "Skróty klawiszowe")
                for index, name in enumerate(tab_names):
                    if index < widget.count():
                        widget.setTabText(index, name)
            if hasattr(widget, "setText") and hasattr(widget, "text"):
                old = widget.text()
                if isinstance(old, str) and old in mapping:
                    widget.setText(mapping[old])
            if hasattr(widget, "setToolTip"):
                old_tip = widget.toolTip()
                if isinstance(old_tip, str) and old_tip in mapping:
                    widget.setToolTip(mapping[old_tip])
            if hasattr(widget, "setPlaceholderText"):
                old_hint = widget.placeholderText()
                if isinstance(old_hint, str) and old_hint in mapping:
                    widget.setPlaceholderText(mapping[old_hint])
            if hasattr(widget, "setWindowTitle"):
                old_title = widget.windowTitle()
                if isinstance(old_title, str) and old_title in mapping:
                    widget.setWindowTitle(mapping[old_title])
            if hasattr(widget, "setTabText"):
                continue
        except (RuntimeError, AttributeError, TypeError):
            pass
